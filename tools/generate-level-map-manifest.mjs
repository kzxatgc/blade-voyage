import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const MAX_LEVEL_COUNT = 99;
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mapsDirectory = resolve(projectRoot, 'public/assets/maps');
const generatedFile = resolve(projectRoot, 'src/shared/generatedLevelMaps.ts');

if (!existsSync(mapsDirectory)) {
  throw new Error(`Map directory does not exist: ${mapsDirectory}`);
}

const mapIndices = readdirSync(mapsDirectory, { withFileTypes: true })
  // Only numbered JSON files are game levels; editor maps may use other names.
  .filter((entry) => entry.isFile() && /^\d+\.json$/.test(entry.name))
  .map((entry) => {
    const mapName = entry.name.slice(0, -'.json'.length);
    const index = Number.parseInt(mapName, 10);
    if (String(index) !== mapName) {
      throw new Error(
        `Level map filename must use a canonical number: ${entry.name}`
      );
    }
    if (index >= MAX_LEVEL_COUNT) {
      throw new Error(
        `Level map "${entry.name}" exceeds the maximum level count of ${MAX_LEVEL_COUNT}.`
      );
    }
    return index;
  })
  .sort((left, right) => left - right);

if (mapIndices.length === 0) {
  throw new Error(`No numbered level maps were found in ${mapsDirectory}.`);
}

for (let expectedIndex = 0; expectedIndex < mapIndices.length; expectedIndex++) {
  if (mapIndices[expectedIndex] !== expectedIndex) {
    throw new Error(
      `Level map numbering must be contiguous from 0; missing "${expectedIndex}.json".`
    );
  }
}

if (mapIndices.length > MAX_LEVEL_COUNT) {
  throw new Error(
    `Found ${mapIndices.length} level maps; the maximum is ${MAX_LEVEL_COUNT}.`
  );
}

const generatedSource = [
  '// Generated by tools/generate-level-map-manifest.mjs. Do not edit.',
  `export const MAX_LEVEL_COUNT = ${MAX_LEVEL_COUNT};`,
  `export const LEVEL_MAP_INDICES = [${mapIndices.join(', ')}] as const;`,
  '',
].join('\n');

mkdirSync(dirname(generatedFile), { recursive: true });
if (
  !existsSync(generatedFile) ||
  readFileSync(generatedFile, 'utf8') !== generatedSource
) {
  writeFileSync(generatedFile, generatedSource);
}
